import assert from 'node:assert/strict';
import {jointAngle,evaluate,smooth,weeklySummary} from './person3.ts';
const p=(x,y,visibility=1)=>({x,y,visibility});
assert.equal(Math.round(jointAngle(p(1,0),p(0,0),p(0,1))),90);
assert.equal(Math.round(jointAngle(p(-1,0),p(0,0),p(1,0))),180);
assert.equal(jointAngle(p(0,0),p(0,0),p(1,0)),null);
assert.equal(jointAngle(p(1,0,0.1),p(0,0),p(0,1)),null);
assert.equal(jointAngle(p(NaN,0),p(0,0),p(0,1)),null);
const r=[{id:'knee',points:['hip','knee','ankle'],min:80,max:100,tolerance:10,below:'Bend less',above:'Bend more',sourceId:'project',evidence:'project-defined'}];
const landmarks={hip:p(1,0),knee:p(0,0),ankle:p(0,1)};
assert.equal(evaluate(landmarks,r).score,100);
assert.equal(evaluate(landmarks,r).status,'correct');
assert.equal(evaluate({},r).score,null);
assert.equal(evaluate({},r).status,'unavailable');
assert.equal(evaluate({hip:p(1,0),knee:p(0,0),ankle:p(1,0)},r).feedback[0],'Bend less');
assert.equal(evaluate(landmarks,[]).score,null);
assert.equal(smooth(80,100,0.5),90);
const w=weeklySummary([{pose_id:1,day_number:1,accuracy_score:80,created_at:'2026-11-20T00:00:00Z'},{pose_id:1,day_number:2,accuracy_score:100,created_at:'2026-11-21T00:00:00Z'}],new Date('2026-11-22T00:00:00Z'));
assert.equal(w.average,90);assert.equal(w.completedAttempts,2);assert.equal(w.practiceSeconds,null);
